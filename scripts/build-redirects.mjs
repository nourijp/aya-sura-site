// Generates public/_redirects and public/_headers (Cloudflare Pages format).
// Inputs: src/config/domains.json, src/data/scan-routes.json
// Runs automatically before `astro build` (see package.json "prebuild").
import fs from 'node:fs';

const domains = JSON.parse(fs.readFileSync('src/config/domains.json', 'utf8'));
const scan = JSON.parse(fs.readFileSync('src/data/scan-routes.json', 'utf8'));
const { storeLive } = domains;

// Redirect loop guard: before cutover the shop lives at legacyOrigin
// (www.ayasura.com). If this site were ever served from that host, store
// redirects would point at themselves. The production Pages project sets
// PRODUCTION_CUTOVER=1 so that build fails loudly instead of looping.
if (process.env.PRODUCTION_CUTOVER === '1' && (!storeLive || !domains.production)) {
  console.error(`\n✖ PRODUCTION_CUTOVER=1 but src/config/domains.json has storeLive=${storeLive}, production=${domains.production}.`);
  console.error('  Both must be true on the production project. Finish migration/CUTOVER_RUNBOOK.md (store.ayasura.com live) first.\n');
  process.exit(1);
}

const STORE = storeLive ? domains.store : domains.legacyOrigin;
const lines = [];
const internal = {}; // same-site redirects also emitted as Astro redirects (work on any static host)
const add = (from, to, code = 301) => {
  lines.push(`${from.padEnd(34)} ${to} ${code}`);
  if (to.startsWith('/') && from.endsWith('/') && !from.includes('*')) internal[from] = to;
};
const section = (t) => lines.push('', `# ${t}`);

lines.push(
  '# GENERATED by scripts/build-redirects.mjs — do not edit by hand.',
  '# Change rules in that script or in src/data/scan-routes.json.',
  `# store target: ${STORE}  (storeLive=${storeLive})`,
  '#',
  '# PRINTED QR CODES (verified by decoding product photos, see migration/qr-test-results.md):',
  '#   Quran Edition box -> https://ayasura.com/about/        (real page, never redirect)',
  '#   Surah Edition box -> https://ayasura.com/qr/cards/se1/  (real page, never redirect)'
);

section('Short links for future QR codes (302 so destinations stay changeable)');
for (const [k, v] of Object.entries(scan)) {
  if (k.startsWith('_')) continue;
  add(`/s/${k}`, v, 302);
  add(`/s/${k}/`, v, 302);
}

section('Spelling / path aliases');
add('/qr/pronunciation/', '/qr/pronounciation/');
add('/qr/pronunciation', '/qr/pronounciation/');
add('/resources/cards/quran-edition/', '/qr/cards/qe1/');
add('/resources/cards/surah-edition/', '/qr/cards/se1/');
add('/resources/cards/', '/qr/');
add('/resources/', '/qr/');

section('Old marketing pages -> new equivalents');
add('/aya/', '/characters/aya/');
add('/aya', '/characters/aya/');
add('/sura/', '/characters/sura/');
add('/sura', '/characters/sura/');
add('/games/', '/qr/games/');
add('/games', '/qr/games/');
add('/cards-by-code/', '/qr/cards/se1/');
add('/collection/flashcards/', '/cards/');
add('/collection/book/', '/books/');
add('/collection/magazine/', '/adventure-club/');
add('/subscribe/', '/adventure-club/');
add('/subscription-plan/', '/adventure-club/');
add('/all-blocks/', '/adventure-club/');
add('/newsletter', '/free/');
add('/newsletter/', '/free/');
add('/form/', '/contact/');
add('/products/', '/shop/');
add('/member-tos-page/', '/terms/');

section('Dead-plugin / placeholder pages (unrendered shortcodes on the old site) -> home');
for (const p of ['member-login', 'member-logout', 'register', 'lost-password', 'dashboard', 'student-registration',
  'instructor-registration', 'public-individual-page', 'default-redirect-page', 'sample-page', 'be-back-soon']) {
  add(`/${p}/`, '/');
}

section(`Shop / account / WordPress plumbing -> ${STORE}`);
for (const p of ['cart', 'checkout', 'my-account', 'my-account-2', 'stripe-checkout-result']) {
  const dest = p === 'my-account-2' ? 'my-account' : p;
  add(`/${p}`, `${STORE}/${dest}/`);
  add(`/${p}/*`, `${STORE}/${dest}/:splat`);
}
for (const p of ['product', 'product-category', 'product-tag']) {
  add(`/${p}/*`, `${STORE}/${p}/:splat`);
}
add('/wp-login.php', `${STORE}/wp-login.php`, 302);
add('/wp-admin', `${STORE}/wp-admin/`, 302);
add('/wp-admin/*', `${STORE}/wp-admin/:splat`, 302);
add('/wp-json/*', `${STORE}/wp-json/:splat`, 302);
add('/xmlrpc.php', `${STORE}/xmlrpc.php`, 302);
add('/feed/', `${STORE}/feed/`, 302);
add('/comments/feed/', `${STORE}/comments/feed/`, 302);
// /wp-content/* is handled by functions/wp-content/[[path]].ts so that the
// preserved audio/image files are served here and anything else falls back.

fs.writeFileSync('public/_redirects', lines.join('\n') + '\n');
fs.writeFileSync('src/data/static-redirects.json', JSON.stringify(internal, null, 2) + '\n');

fs.writeFileSync('public/_headers', [
  '# GENERATED by scripts/build-redirects.mjs',
  '/wp-content/uploads/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '/downloads/*',
  '  Cache-Control: public, max-age=86400',
  '/images/*',
  '  Cache-Control: public, max-age=604800',
  ''
].join('\n'));

fs.writeFileSync('public/robots.txt', domains.production
  ? `User-agent: *\nAllow: /\nDisallow: /qr/audio/\n\nSitemap: ${domains.apex}/sitemap-index.xml\n`
  : 'User-agent: *\nDisallow: /\n');

const n = lines.filter((l) => l && !l.startsWith('#')).length;
console.log(`build-redirects: ${n} rules -> public/_redirects (store=${STORE})`);
